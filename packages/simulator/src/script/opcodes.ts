const NAMES = new Map<number, string>(Object.entries(Op).map(([n, v]) => [v, `Op${n}`]));

export function opcodeName(op: number): string {
  if (op >= 0x01 && op <= 0x4b) return `OpData${op}`;
  if (op >= 0x52 && op <= 0x60) return `Op${op - 0x50}`;
  return NAMES.get(op) ?? `OpUnknown${op}`;
}

/**
 * Opcodes rusty-kaspa v2.1.0 enables but the simulator does not execute, because reproducing them needs state the
 * simulator does not have: the ZK precompile verifiers (Groth16 / RISC0, `zk_precompiles/`) and the sequencing
 * commitment of a chain block (`OpChainblockSeqCommit`, which reads the node's chain index). A script that EXECUTES one
 * fails with SCRIPT_UNSUPPORTED_OPCODE — never silently passes. Every other opcode the node enables is implemented in
 * `vm.ts`; the ones the node disables or reserves fail exactly as they do there (see `DISABLED_OPCODES`).
 */
export const UNSUPPORTED_OPCODES = new Set<number>([Op.ZkPrecompile, Op.ChainblockSeqCommit]);

/**
 * `is_disabled()` in `opcodes/mod.rs:134-136`: rejected with OpcodeDisabled wherever they appear in a script, even in a
 * branch that is not executed (`lib.rs:621-623`).
 */
export const DISABLED_OPCODES = new Set<number>([Op.Left, Op.Right, Op.TwoMul, Op.TwoDiv, Op.LShift, Op.RShift]);

/** `always_illegal()` in `opcodes/mod.rs:138-140`: rejected with OpcodeReserved wherever they appear (`lib.rs:625-627`). */
export const ALWAYS_ILLEGAL_OPCODES = new Set<number>([Op.VerIf, Op.VerNotIf]);
