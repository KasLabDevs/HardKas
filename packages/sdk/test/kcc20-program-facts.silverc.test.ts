import { describe, it, expect, beforeAll } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { KCC20_DEFAULT_CONFIG, compileSilverScript, parseSilverSourceAst, type SilArtifactValue } from "@hardkas/core";
import { v1ContractFactsFromArtifact, type V1ContractFacts } from "@hardkas/accounts";
import { kcc20ProgramFacts, kcc20StateOfProgramState } from "../src/kcc20.js";

// -----------------------------------------------------------------------------
// R3-A3 · the v1 engine's facts for a KCC-20 program (kcc20ProgramFacts). The reference program (argent-lang/kcc20-reference
// @ 27f8403f, KCC20.sil, generated by argentc) carries no silverc covenant declaration: its covenant shape is what KCC-20
// and its kcc20.json say. The facts add exactly that — a cov binding whose leader calls `transfer` and whose delegates call
// `transfer_delegator`, bounded by max_token_inputs / max_token_outputs — to the contract the pinned silverc reproduces,
// and refuse a contract that is not such a program (other entries or tags, no KCC20State fields, declarations of its
// own, as the silverscript v1.0.0 example KCC20 has). silverc level (the pinned silverc); HARDKAS_TEST_KCC20_REFERENCE names
// the reference checkout (without it the suite FAILS, KCC20_REFERENCE_MISSING; HARDKAS_TEST_SKIP_KCC20_REFERENCE=1 skips).
// -----------------------------------------------------------------------------

const REF = process.env.HARDKAS_TEST_KCC20_REFERENCE ?? "";
const SKIP_REF = process.env.HARDKAS_TEST_SKIP_KCC20_REFERENCE === "1";
const SIL_SHA256 = "9c61d62a1b90ad541bbf5c48ec53faaff1826cbc6f26bd42fa429df5c295316c";
const P2 = path.resolve(__dirname, "../../accounts/test/fixtures/v1-engine/phase2");
const zeros = (n: number) => new Array(n).fill(0);

async function factsOf(source: string, ctor: SilArtifactValue[], contractName: string): Promise<V1ContractFacts> {
  const compiled = await compileSilverScript({ source, constructorArgs: ctor });
  const ast = await parseSilverSourceAst(source);
  return v1ContractFactsFromArtifact({ compileRecordHash: "00".repeat(32), artifactSha256: compiled.provenance.artifactSha256, artifact: compiled.artifact, contractName, constructorArgs: ctor, ast: ast as any });
}

describe.skipIf(SKIP_REF)("R3-A3 · kcc20ProgramFacts: the engine's facts for a KCC-20 program", () => {
  let reference: V1ContractFacts;
  beforeAll(async () => {
    if (REF === "") {
      throw new Error(
        "KCC20_REFERENCE_MISSING: set HARDKAS_TEST_KCC20_REFERENCE to a checkout of argent-lang/kcc20-reference @ 27f8403f " +
          "(or HARDKAS_TEST_SKIP_KCC20_REFERENCE=1 to skip this suite explicitly)"
      );
    }
    const sil = fs.readFileSync(path.join(REF, "fixtures", "public-mint", "sil", "KCC20.sil"));
    expect(createHash("sha256").update(sil).digest("hex")).toBe(SIL_SHA256);
    const ctor: SilArtifactValue[] = [
      { kind: "bytes", value: zeros(32) },
      { kind: "int", value: 0n },
      { kind: "bytes", value: zeros(32) },
      { kind: "byte", value: 0 },
      { kind: "byte", value: 0 },
      { kind: "bytes", value: zeros(32) },
      { kind: "bytes", value: zeros(32) }
    ];
    reference = await factsOf(sil.toString("utf8"), ctor, "KCC20");
  }, 120_000);

  it("F1 the reference program has no silverc declaration of its own; the KCC-20 facts give it the KCC-20 shape and change nothing else", () => {
    expect(reference.declarations).toEqual([]);
    expect(reference.artifact.contracts.KCC20!.cov_decl_to_abi ?? {}).toEqual({});
    const f = kcc20ProgramFacts(reference);
    expect(f.declarations).toEqual([{ policy: "transfer", form: "kcc20", binding: "cov", from: KCC20_DEFAULT_CONFIG.maxTokenInputs, to: KCC20_DEFAULT_CONFIG.maxTokenOutputs, mode: "verification" }]);
    expect(f.artifact.contracts.KCC20!.cov_decl_to_abi).toEqual({ transfer: "transfer" });
    expect(f.artifact.contracts.KCC20!.delegate_entry_abi).toBe("transfer_delegator");
    expect(f.delegateFunction).toBe("transfer_delegator");
    // the program itself is the one silverc reproduced: bytecode, lock, template, state, ABI entries
    for (const k of ["bytecodeHex", "lock", "templateHash", "state", "compileRecordHash", "artifactSha256", "contractName"] as const) expect(f[k]).toEqual(reference[k]);
    expect(f.artifact.contracts.KCC20!.entries).toEqual(reference.artifact.contracts.KCC20!.entries);
    expect(f.artifact.contracts.KCC20!.compiled).toEqual(reference.artifact.contracts.KCC20!.compiled);
    // the input facts are not mutated
    expect(reference.artifact.contracts.KCC20!.cov_decl_to_abi ?? {}).toEqual({});
  });

  it("F2 the bounds come from the program's KCC-20 artifact configuration", () => {
    const f = kcc20ProgramFacts(reference, { ...KCC20_DEFAULT_CONFIG, maxTokenInputs: 2, maxTokenOutputs: 1 });
    expect([f.declarations[0]!.from, f.declarations[0]!.to]).toEqual([2, 1]);
  });

  it("F3 a configuration whose entrypoints the program does not have, or whose dispatch tags differ, is refused (KCC20_PROGRAM_INVALID)", () => {
    expect(() => kcc20ProgramFacts(reference, { ...KCC20_DEFAULT_CONFIG, transferEntrypoint: "send", delegatorEntrypoint: "send_delegator" })).toThrow(/KCC20_PROGRAM_INVALID|no entry 'send'/);
    try {
      kcc20ProgramFacts(reference, { ...KCC20_DEFAULT_CONFIG, transferEntrypoint: "send", delegatorEntrypoint: "send_delegator" });
    } catch (e: any) {
      expect(e.code).toBe("KCC20_PROGRAM_INVALID");
    }
  });

  it("F4 the silverscript v1.0.0 example KCC20 (its own covenant declarations, another state layout) is not a KCC-20 program: refused", () => {
    const artifact = JSON.parse(fs.readFileSync(path.join(P2, "kcc20.artifact.json"), "utf8"));
    const ast = JSON.parse(fs.readFileSync(path.join(P2, "kcc20.ast.json"), "utf8"));
    const ctor: SilArtifactValue[] = [{ kind: "bytes", value: zeros(32) }, { kind: "int", value: 1000n }, { kind: "byte", value: 0 }, { kind: "bool", value: false }, { kind: "int", value: 2n }, { kind: "int", value: 2n }];
    const example = v1ContractFactsFromArtifact({ compileRecordHash: "00".repeat(32), artifactSha256: "00".repeat(32), artifact, contractName: "KCC20", constructorArgs: ctor, ast });
    let code = "";
    try {
      kcc20ProgramFacts(example);
    } catch (e: any) {
      code = e.code;
    }
    expect(code).toBe("KCC20_PROGRAM_INVALID");
  });

  it("F5 a program state reads back as its KCC20State; a state without the KCC20State fields is refused (KCC20_STATE_INVALID)", () => {
    const owner = Array.from({ length: 32 }, (_, i) => i);
    const s = kcc20StateOfProgramState({
      gen__kcc20_template: { kind: "bytes", value: zeros(32) },
      amount: { kind: "int", value: "9007199254740993" },
      owner: { kind: "bytes", value: owner },
      owner_scheme: { kind: "byte", value: 1 },
      borrow_scheme: { kind: "byte", value: 0 },
      borrow_guard: { kind: "bytes", value: zeros(32) },
      extension_commitment: { kind: "bytes", value: zeros(32) }
    });
    expect(s.amount).toBe(9007199254740993n);
    expect(s.owner).toBe(Buffer.from(owner).toString("hex"));
    expect(s.ownerScheme).toBe(1);
    let code = "";
    try {
      kcc20StateOfProgramState({ value: { kind: "int", value: "1" } });
    } catch (e: any) {
      code = e.code;
    }
    expect(code).toBe("KCC20_STATE_INVALID");
  });
});
