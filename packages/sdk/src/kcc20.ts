// ---------------------------------------------------------------------------------------------------------------------
// R3-A3 · KCC-20 tokens on a node, through the SDK's v1 engine (sdk.covenants). No second transaction builder: the
// engine plans, checks (F1.4), signs and sends (F1.6) every transaction here. What this module adds:
//
// 1. The engine's facts for a KCC-20 program. A KCC-20 program such as the linked reference (argent-lang/kcc20-reference
//    KCC20.sil, generated by argentc) carries no silverc covenant declaration: its covenant shape is what KCC-20 and the
//    program's KCC-20 artifact (kcc20.json) say — a cov binding whose leader calls `transfer` and whose other token inputs
//    call `transfer_delegator`, at most max_token_inputs inputs and max_token_outputs continuations. Those facts are given
//    to the engine (its injectable `facts`) for a contract that has exactly those entries with KCC-1's dispatch tags and
//    the six KCC20State fields in its runtime state; everything else the engine checks as for any covenant (the inputs
//    as the node lists them, one template, each continuation the template holding its declared state, the bindings, the
//    cardinalities, the fee floor).
// 2. The owner signature inside the witness. KCC-20's witness is a `byte[]` (path byte, then the owner authentication), not
//    a `sig` parameter the engine could fill: the engine plans the transfer with placeholder signatures of the same size,
//    each owner signs (SIGHASH_ALL) the engine's own unsigned transaction — the v1 sighash and transaction id do not cover
//    signature scripts — and the engine plans it again with the signatures in place: same mass, same fee, same txid,
//    checked before anything is signed by the engine.
// 3. The KCC-20 rules (kcc20CheckTransfer, the model `hardkas kcc20 check` runs) before any key is read — structure,
//    cardinality, conservation, owner and borrow schemes, extension commitment, each owner's key — and again with the
//    signatures made. A transfer they reject is refused locally (KCC20_TRANSFER_REJECTED); the program on chain is the
//    final judge of everything else.
//
// Scope: owners p2pk-schnorr/v1 (0x00) and p2pkh-schnorr/v1 (0x01) sign here (the normal path); a borrowed receive and
// the p2pkh-ecdsa, p2sh and covenant-id owner schemes are refused before any key (KCC20_OWNER_SCHEME_UNSUPPORTED). New
// outputs are p2pk-schnorr/v1 owners. A token's outputs are found through this workspace's records of its covenant
// (the node has no query by covenant id), each one listed unspent at the node with its covenant id and its state checked
// against its address.
// ---------------------------------------------------------------------------------------------------------------------

