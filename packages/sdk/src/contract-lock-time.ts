import { HardkasError } from "@hardkas/core";
import { LOCK_TIME_THRESHOLD, describeLockTime, lockTimeKindOfValue, type LockTimeKind } from "@hardkas/tx-builder";

/*
 * R3-F · CLTV · what a SilverScript entry asks of the lock time of the transaction that spends through it, read from the
 * compiled contract (the official parser's AST and the arguments HardKAS has), and checked before anything is signed.
 *
 * silverc v1.0.0 (probed, R3-F): `require(tx.daa >= x)` compiles to `x OP_DUP 0 <500000000000> OP_WITHIN OP_VERIFY
 * OP_CHECKLOCKTIMEVERIFY`, and `require(tx.time >= x)` (x of type `temporal`) to `x OP_DUP <500000000000>
 * OP_GREATERTHANOREQUAL OP_VERIFY OP_CHECKLOCKTIMEVERIFY`; a constant x of the other kind does not compile ("tx.daa value
 * must satisfy 0 <= value < LOCK_TIME_THRESHOLD", "tx.time value must be at least LOCK_TIME_THRESHOLD"). So the statement
 * fixes the kind of x, and OpCheckLockTimeVerify (rusty-kaspa) refuses a transaction whose lock time is of the other kind
 * ("mismatched locktime types") or below x ("Unsatisfied lock time"): both seen on rusty-kaspad v2.1.0 (R3-B1 S-1, R3-F).
 * A transaction without a lock time has lock time 0, which is of the DAA-score kind.
 *
 * Only the entry's top-level statements are read: they run on every spend through it. A statement under `if`, in a loop
 * or in a helper function is not read (it may not run). A covenant's entries are generated by silverc around its policy:
 * for the leader's entry of a policy, the policy function's top-level statements are read (`policy`); a delegate's entry
 * is not read. x is known when it is an integer literal, or a parameter (of the constructor or of the entry) that no
 * statement of the entry redefines and whose int value the caller gives; otherwise only the kind is checked. Nothing else
 * is assumed: the node decides the rest.
 */

/** What one top-level `require(tx.daa >= x)` / `require(tx.time >= x)` statement of an entry asks of the lock time. */
export interface ContractEntryLockTimeRequirement {
  /** "daaScore" for `tx.daa`, "timestampMs" for `tx.time`. */
  readonly kind: LockTimeKind;
  /** x, when HardKAS can read it (an integer literal, or a parameter whose int value it was given). */
  readonly atLeast?: bigint | undefined;
  /** The statement as the source writes it. */
  readonly statement: string;
}

type Ast = Record<string, any>;

function namesOf(params: unknown): string[] {
  return Array.isArray(params) ? params.map((p: any) => (typeof p?.name === "string" ? p.name : "")) : [];
}

/** Every name a statement of the function defines or assigns (a local variable that would hide a parameter). */
function definedNames(body: unknown): Set<string> {
  const out = new Set<string>();
  const visit = (node: unknown): void => {
    if (node === null || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const item of node) visit(item);
      return;
    }
    const n = node as Ast;
    const isCall = n.kind === "call" || n.kind === "function_call";
    if (!isCall && n.kind !== "identifier" && n.data && typeof n.data === "object") {
      if (typeof n.data.name === "string") out.add(n.data.name);
      if (Array.isArray(n.data.names)) for (const x of n.data.names) if (typeof x === "string") out.add(x);
      if (typeof n.data.target === "string") out.add(n.data.target);
    }
    for (const value of Object.values(n)) visit(value);
  };
  visit(body);
  return out;
}

/** The value of an `int` argument (SilverScript artifact value or v1 argument), else undefined. */
function intArgOf(arg: unknown): bigint | undefined {
  const a = arg as { kind?: unknown; value?: unknown } | null | undefined;
  if (a?.kind !== "int") return undefined;
  const v = a.value;
  try {
    if (typeof v === "bigint") return v;
    if (typeof v === "number" && Number.isSafeInteger(v)) return BigInt(v);
    if (typeof v === "string" && /^-?\d{1,20}$/.test(v)) return BigInt(v);
  } catch {
    return undefined;
  }
  return undefined;
}

/**
 * The lock-time requirements of `entry` (a function of the contract's AST, `silverc --ast-only`): one per top-level
 * `require(tx.daa >= x)` / `require(tx.time >= x)` statement. `constructorArgs` and `entryArgs` are the values in the
 * order of the contract's and the entry's parameters, as far as the caller has them (missing ones leave x unknown).
 * An entry the AST does not have (a covenant's generated entry) has no requirements HardKAS reads.
 */
export function contractEntryLockTimeRequirements(input: {
  readonly ast: unknown;
  readonly entry: string;
  readonly constructorArgs?: ReadonlyArray<unknown> | undefined;
  readonly entryArgs?: ReadonlyArray<unknown> | undefined;
  /**
   * A covenant transition: the policy (a `#[covenant…]` function) whose generated entry `entry` is. Its top-level
   * statements are read instead; its parameters are never bound to the entry's arguments (an x that is one is unknown).
   */
  readonly policy?: string | undefined;
}): ContractEntryLockTimeRequirement[] {
  const ast = input.ast as Ast | null | undefined;
  const functions: Ast[] = Array.isArray(ast?.functions) ? ast!.functions : [];
  const isCovenant = (f: Ast) => Array.isArray(f?.attributes) && f.attributes.some((a: any) => Array.isArray(a?.path) && a.path[0] === "covenant");
  const fn =
    input.policy !== undefined
      ? functions.find((f) => f?.name === input.policy && isCovenant(f))
      : functions.find((f) => f?.name === input.entry && f?.entrypoint === true);
  const entryArgs = input.policy !== undefined ? undefined : input.entryArgs;
  if (!fn || !Array.isArray(fn.body)) return [];
  const ctorParams = namesOf(ast?.params);
  const entryParams = namesOf(fn.params);
  const defined = definedNames(fn.body);
  const valueOf = (expr: Ast | undefined): bigint | undefined => {
    if (expr?.kind === "int") {
      const d = expr.data;
      if (typeof d === "number" && Number.isSafeInteger(d) && d >= 0) return BigInt(d);
      if (typeof d === "string" && /^\d{1,20}$/.test(d)) return BigInt(d);
      return undefined;
    }
    if (expr?.kind === "identifier" && typeof expr.data === "string") {
      const name = expr.data;
      if (defined.has(name)) return undefined;
      const inEntry = entryParams.indexOf(name);
      const inCtor = ctorParams.indexOf(name);
      if (inEntry >= 0 && inCtor >= 0) return undefined;
      if (inEntry >= 0) return intArgOf(entryArgs?.[inEntry]);
      if (inCtor >= 0) return intArgOf(input.constructorArgs?.[inCtor]);
    }
    return undefined;
  };
  const out: ContractEntryLockTimeRequirement[] = [];
  for (const statement of fn.body as Ast[]) {
    if (statement?.kind !== "require_tx_daa" && statement?.kind !== "require_tx_time") continue;
    const atLeast = valueOf(statement.data?.expr);
    out.push({
      kind: statement.kind === "require_tx_daa" ? "daaScore" : "timestampMs",
      ...(atLeast !== undefined ? { atLeast } : {}),
      statement: String(statement.data?.span ?? (statement.kind === "require_tx_daa" ? "require(tx.daa >= …)" : "require(tx.time >= …)"))
    });
  }
  return out;
}

/**
 * The spend's lock time (0 when it has none) against an entry's requirements, before anything is signed:
 * LOCK_TIME_KIND_MISMATCH when it is not of the kind a statement fixes (a time for `tx.daa`; a DAA score, or none, for
 * `tx.time`), LOCK_TIME_BELOW_ENTRY_REQUIREMENT when it is below an x HardKAS can read. The node would refuse either
 * transaction whatever its time (OpCheckLockTimeVerify), and with HardKAS's one submission per txId that refusal would be
 * final for it.
 */
export function assertLockTimeMeetsContractEntry(lockTime: bigint, requirements: readonly ContractEntryLockTimeRequirement[], what: string): void {
  const kind: LockTimeKind = lockTimeKindOfValue(lockTime) ?? "daaScore";
  const stated = lockTime === 0n ? "no lock time (lock time 0)" : `lock time ${describeLockTime(lockTime)}`;
  for (const r of requirements) {
    if (r.kind !== kind) {
      throw new HardkasError(
        "LOCK_TIME_KIND_MISMATCH",
        `${what} runs \`${r.statement}\`, which needs a ${r.kind === "daaScore" ? `DAA-score lock time (below ${LOCK_TIME_THRESHOLD})` : `time lock time (milliseconds, at or above ${LOCK_TIME_THRESHOLD})`}, ` +
          `and the spend has ${stated}. The node refuses it (OpCheckLockTimeVerify: mismatched locktime types). ` +
          `Give ${r.kind === "daaScore" ? "a DAA-score lock time (lockTime { daaScore }, --lock-time-daa)" : "a time lock time (lockTime { timestampMs }, --lock-time-ms)"}. Nothing was signed.`,
        { metadata: { required: r.kind, lockTime: lockTime.toString(), statement: r.statement } }
      );
    }
    if (r.atLeast !== undefined && lockTime < r.atLeast) {
      throw new HardkasError(
        "LOCK_TIME_BELOW_ENTRY_REQUIREMENT",
        `${what} runs \`${r.statement}\`, which needs a lock time of at least ${describeLockTime(r.atLeast)}, and the spend has ${stated}. ` +
          `The node refuses it (OpCheckLockTimeVerify: unsatisfied lock time). Give a lock time of at least ${r.atLeast}. Nothing was signed.`,
        { metadata: { required: r.kind, atLeast: r.atLeast.toString(), lockTime: lockTime.toString(), statement: r.statement } }
      );
    }
  }
}
