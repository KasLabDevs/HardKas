// BETA-FIX W4 · old hardkas.dev/docs URLs keep working after the pages moved into the repository's docs/.
// apps/docs/redirects.json holds every published URL of the hand-written pages before the move ("legacy", from the
// sitemap of 20-nov-2026) and the map of moved pages ("redirects"). After the build this plugin:
//   - fails when a legacy URL is neither a page nor redirected, when a redirect points at no page, or when a page is
//     also redirected (so the map can never drift from the site);
//   - writes `_redirects` (Cloudflare: 301, both with and without the trailing slash) into the build output; the
//     unified site build (scripts/build-unified-site.mjs) moves it to the root of dist/site, where Cloudflare reads it;
//   - writes a small HTML redirect page at every old path, so the redirect also works on a host that ignores
//     `_redirects` (and in scripts/test-unified-site.mjs).
// No dependency.
import fs from "node:fs";
import path from "node:path";

const trim = (p) => (p.length > 1 ? p.replace(/\/+$/, "") : p);

function escapeHtml(s) {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

/** @param {{ file: string }} options */
export default function redirectsPlugin(_context, options) {
  const map = JSON.parse(fs.readFileSync(options.file, "utf8"));
  return {
    name: "hardkas-docs-redirects",
    async postBuild({ routesPaths, outDir, baseUrl, siteConfig }) {
      const base = baseUrl.endsWith("/") ? baseUrl : `${baseUrl}/`;
      const routes = new Set(
        routesPaths
          .filter((r) => r.startsWith(base) || `${r}/` === base)
          .map((r) => trim(`/${r.slice(base.length)}`))
      );
      routes.add("/");
      const errors = [];
      const from = new Map();
      for (const r of map.redirects) {
        const f = trim(r.from);
        const to = trim(r.to.split("#")[0]);
        if (from.has(f)) errors.push(`redirect from ${r.from} is listed twice`);
        from.set(f, r.to);
        if (routes.has(f)) errors.push(`redirect from ${r.from} shadows a page that exists`);
        if (!routes.has(to)) errors.push(`redirect ${r.from} -> ${r.to}: no page at ${r.to}`);
      }
      for (const legacy of map.legacy) {
        const l = trim(legacy);
        if (!routes.has(l) && !from.has(l)) errors.push(`legacy URL ${legacy} is neither a page nor redirected`);
      }
      if (errors.length > 0) {
        throw new Error(`[docs-redirects] ${errors.length} problem(s) in ${path.basename(options.file)}:\n  ${errors.join("\n  ")}`);
      }

      const site = (siteConfig.url ?? "").replace(/\/+$/, "");
      const lines = [];
      for (const [f, to] of [...from.entries()].sort(([a], [b]) => a.localeCompare(b))) {
        const target = `${base}${to.replace(/^\//, "")}`;
        const old = `${base}${f.replace(/^\//, "")}`;
        lines.push(`${old} ${target} 301`, `${old}/ ${target} 301`);
        const page = path.join(outDir, ...f.split("/").filter(Boolean), "index.html");
        fs.mkdirSync(path.dirname(page), { recursive: true });
        const t = escapeHtml(target);
        fs.writeFileSync(
          page,
          `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Moved</title>` +
            `<link rel="canonical" href="${escapeHtml(site + target)}"><meta name="robots" content="noindex">` +
            `<meta http-equiv="refresh" content="0; url=${t}"></head><body>` +
            `<script>location.replace(${JSON.stringify(target)} + (${JSON.stringify(target.includes("#"))} ? "" : location.hash));</script>` +
            `<p>This page moved to <a href="${t}">${t}</a>.</p></body></html>\n`
        );
      }
      fs.writeFileSync(
        path.join(outDir, "_redirects"),
        `# Generated by apps/docs/plugins/redirects.mjs from apps/docs/redirects.json. Do not edit.\n${lines.join("\n")}\n`
      );
      console.log(`[docs-redirects] ${from.size} redirect(s) written; ${map.legacy.length} legacy URL(s) all resolve.`);
    }
  };
}
