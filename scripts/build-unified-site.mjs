/**
 * HardKAS Unified Web Deployment Generator
 *
 * Compiles Docusaurus with baseUrl: '/docs/', copies the landing page to root,
 * copies documentation into /docs/, and produces a unified, verified sitemap,
 * robots.txt, and llms.txt in dist/site.
 */
import fs from "node:fs";
import path from "node:path";
import { execFileSync, execSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
// BETA-FIX W4: `--out <dir>` assembles somewhere else than dist/site (the deployed folder), and `--no-docs-build` reuses
// the last apps/docs/build, so the assembly can be checked (scripts/test-unified-site.mjs --dir <dir>) without touching
// what is deployed. Without flags nothing changes.
const outAt = process.argv.indexOf("--out");
const DIST_SITE = outAt > -1 && process.argv[outAt + 1] ? path.resolve(process.argv[outAt + 1]) : path.join(ROOT, "dist", "site");
const SITE_SRC = path.join(ROOT, "site");
const DOCS_BUILD = path.join(ROOT, "apps", "docs", "build");

console.log("=== Building HardKAS Unified Web Distribution ===");

// 1. Build Docusaurus docs
if (process.argv.includes("--no-docs-build")) {
  console.log("\n[1/5] Reusing the last Docusaurus build (apps/docs/build)...");
  if (!fs.existsSync(path.join(DOCS_BUILD, "index.html"))) throw new Error("apps/docs/build has no build: run without --no-docs-build");
} else {
  console.log("\n[1/5] Building Docusaurus documentation (@hardkas/docs)...");
  execSync("pnpm --filter @hardkas/docs build", {
    cwd: ROOT,
    stdio: "inherit"
  });
}

// 2. Prepare dist/site directory
console.log("\n[2/5] Preparing clean distribution directory (dist/site)...");
if (fs.existsSync(DIST_SITE)) {
  fs.rmSync(DIST_SITE, { recursive: true, force: true });
}
fs.mkdirSync(DIST_SITE, { recursive: true });

// 3. Copy Landing page and root assets
console.log("\n[3/5] Deploying Landing Page and Root Assets to dist/site/...");
fs.copyFileSync(path.join(SITE_SRC, "index.html"), path.join(DIST_SITE, "index.html"));

// Copy any static assets from site/ if they exist (pdf, images, etc.)
for (const file of fs.readdirSync(SITE_SRC)) {
  if (file.endsWith(".pdf") || file.endsWith(".png") || file.endsWith(".ico") || file.endsWith(".svg") || file.startsWith("_")) {
    fs.copyFileSync(path.join(SITE_SRC, file), path.join(DIST_SITE, file));
    console.log(`  Copied root asset: ${file}`);
  }
}

// 4. Copy Docusaurus build output into dist/site/docs
console.log("\n[4/5] Deploying Docusaurus to dist/site/docs/...");
const distDocs = path.join(DIST_SITE, "docs");

function copyDirRecursive(src, dest) {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

copyDirRecursive(DOCS_BUILD, distDocs);

// BETA-FIX W4: the docs build writes its redirects (old /docs/ URLs of pages that moved into the repository's docs/,
// apps/docs/redirects.json) to its own _redirects. Cloudflare reads _redirects only at the root of the deployed
// directory, so they are appended to the landing page's root _redirects instead of staying under /docs/.
// SEO-2026-11-22: Cloudflare Pages counts every rule that comes after the first dynamic one (a splat `*` or a `:name`
// placeholder) as dynamic, and applies at most 100 dynamic rules: with the landing page's splats first, the docs rules
// past the 100th were silently ignored (40 of 86 old URLs got no 301 on the live site). Static rules now come first,
// dynamic ones last; within each group the order of the files is kept. No docs rule overlaps a landing rule.
const docsRedirects = path.join(distDocs, "_redirects");
if (fs.existsSync(docsRedirects)) {
  const rootRedirects = path.join(DIST_SITE, "_redirects");
  const lines = [
    ...(fs.existsSync(rootRedirects) ? fs.readFileSync(rootRedirects, "utf8").split(/\r?\n/) : []),
    ...fs.readFileSync(docsRedirects, "utf8").split(/\r?\n/)
  ].filter((l) => l.trim() && !l.trim().startsWith("#"));
  const isDynamic = (l) => /[*:]/.test(l.trim().split(/\s+/)[0] ?? "");
  const staticRules = lines.filter((l) => !isDynamic(l));
  const dynamicRules = lines.filter(isDynamic);
  if (dynamicRules.length > 100) throw new Error(`_redirects: ${dynamicRules.length} dynamic rules; Cloudflare Pages applies 100`);
  if (staticRules.length > 2000) throw new Error(`_redirects: ${staticRules.length} static rules; Cloudflare Pages applies 2000`);
  fs.writeFileSync(
    rootRedirects,
    `# Generated by scripts/build-unified-site.mjs from site/_redirects and apps/docs/redirects.json.\n` +
      `# Static rules first: Cloudflare Pages counts every rule after the first dynamic one as dynamic (limit 100).\n` +
      `${staticRules.join("\n")}\n${dynamicRules.join("\n")}\n`
  );
  fs.rmSync(docsRedirects);
  console.log(`  Wrote dist/site/_redirects: ${staticRules.length} static rule(s), then ${dynamicRules.length} dynamic rule(s)`);
}

// Copy standalone /ide/ landing page if present
const ideSrc = path.join(SITE_SRC, "ide");
if (fs.existsSync(ideSrc)) {
  copyDirRecursive(ideSrc, path.join(DIST_SITE, "ide"));
  console.log("  Deployed IDE landing page to dist/site/ide/");
}

// SEO-2026-11-21: without a top-level 404.html, Cloudflare Pages treats the site as a single-page app and answers every
// unknown URL with the landing page and HTTP 200 (soft 404s). The docs' own 404 page (absolute /docs/ assets) is served
// at the root as well, so an unknown URL anywhere gets a real 404.
const docs404 = path.join(DOCS_BUILD, "404.html");
if (fs.existsSync(docs404) && !fs.existsSync(path.join(DIST_SITE, "404.html"))) {
  fs.copyFileSync(docs404, path.join(DIST_SITE, "404.html"));
  console.log("  Copied the docs 404 page to dist/site/404.html");
}

// SEO-2026-11-21: the Markdown source of every published page, for AI agents (a page is a few KB of Markdown against
// 24-35 KB of HTML), as docs.kaspa.org does. /md/ mirrors docs/ (so the pages' relative .md links keep working) plus the
// generated CLI reference under /md/reference/cli/. A `noindex` header keeps these copies out of search results; the
// HTML pages stay the canonical ones.
const MD_UNPUBLISHED = new Set(["internal", "community", "proposals", "examples"]);
const distMd = path.join(DIST_SITE, "md");
let mdCount = 0;
function copyMarkdown(src, dest, top = true) {
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name.startsWith("_") || entry.name.startsWith(".")) continue;
    if (top && entry.isDirectory() && MD_UNPUBLISHED.has(entry.name)) continue;
    const s = path.join(src, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) copyMarkdown(s, d, false);
    else if (entry.name.endsWith(".md")) {
      fs.mkdirSync(dest, { recursive: true });
      fs.copyFileSync(s, d);
      mdCount++;
    }
  }
}
copyMarkdown(path.join(ROOT, "docs"), distMd);
copyMarkdown(path.join(ROOT, "apps", "docs", "reference", "cli"), path.join(distMd, "reference", "cli"));
const headersFile = path.join(DIST_SITE, "_headers");
const headersHead = fs.existsSync(headersFile) ? fs.readFileSync(headersFile, "utf8").replace(/\s*$/, "\n") : "";
fs.writeFileSync(
  headersFile,
  `${headersHead}# Generated by scripts/build-unified-site.mjs: Markdown copies for agents, not for search results.\n/md/*\n  Content-Type: text/markdown; charset=utf-8\n  X-Robots-Tag: noindex\n`
);
console.log(`  Copied ${mdCount} Markdown pages to dist/site/md/ (noindex via _headers)`);

// 5. Build Unified Sitemap, robots.txt, and llms.txt
console.log("\n[5/5] Generating unified sitemap.xml, robots.txt, and llms.txt...");

const today = new Date().toISOString().split("T")[0];
const isValidDate = (d) => typeof d === "string" && /^\d{4}-\d{2}-\d{2}$/.test(d) && d <= today;

/**
 * Index last commit dates (%cs = YYYY-MM-DD) for all tracked files under site/, docs/ (the hand-written pages the
 * docs site renders) and apps/docs/reference/ (the generated references) in a single git invocation. If git is
 * unavailable, returns an empty map so <lastmod> is omitted.
 */
function buildGitLastModifiedMap() {
  const map = new Map();
  try {
    const out = execFileSync(
      "git",
      ["log", "--name-only", "--format=DATE:%cs", "--", "site/", "docs/", "apps/docs/reference/"],
      { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
    );
    let currentDate = null;
    for (const rawLine of out.split(/\r?\n/)) {
      const line = rawLine.trim();
      if (!line) continue;
      if (line.startsWith("DATE:")) {
        const d = line.slice(5).trim();
        currentDate = isValidDate(d) ? d : null;
      } else if (currentDate) {
        const normalized = line.replace(/\\/g, "/");
        if (!map.has(normalized)) {
          map.set(normalized, currentDate);
        }
      }
    }
  } catch {
    // Git unavailable or not a git repository: omit <lastmod> rather than inventing dates.
  }
  return map;
}

const gitDates = buildGitLastModifiedMap();

function gitLastModified(relPath) {
  return gitDates.get(relPath.replace(/\\/g, "/")) ?? null;
}

function resolveDocSourceDate(url) {
  const prefix = "https://hardkas.dev/docs";
  if (!url.startsWith(prefix)) return null;
  const rel = url.slice(prefix.length).replace(/^\/+|\/+$/g, "");
  // the generated references live in apps/docs/reference/{cli,sdk}; every other page is docs/<path>
  const base = /^reference\/(cli|sdk)(\/|$)/.test(rel) ? "apps/docs" : "docs";
  const candidates = rel
    ? [
        `${base}/${rel}.md`,
        `${base}/${rel}.mdx`,
        `${base}/${rel}/index.md`,
        `${base}/${rel}/index.mdx`,
        `${base}/${rel}/README.md`
      ]
    : ["docs/README.md"];
  for (const c of candidates) {
    const d = gitLastModified(c);
    if (d) return d;
  }
  return null;
}

function lastmodXml(date) {
  return isValidDate(date) ? `\n    <lastmod>${date}</lastmod>` : "";
}

// Read URLs (and any existing valid <lastmod>) from Docusaurus generated sitemap
const docusaurusSitemapPath = path.join(DOCS_BUILD, "sitemap.xml");
const docEntries = [];
const seenUrls = new Set();
if (fs.existsSync(docusaurusSitemapPath)) {
  const content = fs.readFileSync(docusaurusSitemapPath, "utf8");
  const urlBlockRegex = /<url>([\s\S]*?)<\/url>/g;
  let m;
  while ((m = urlBlockRegex.exec(content)) !== null) {
    const block = m[1];
    const locMatch = /<loc>([^<]+)<\/loc>/.exec(block);
    if (!locMatch) continue;
    const url = locMatch[1];
    if (seenUrls.has(url)) continue;
    seenUrls.add(url);
    const lmMatch = /<lastmod>([^<]+)<\/lastmod>/.exec(block);
    const docusaurusLastmod = lmMatch && isValidDate(lmMatch[1].slice(0, 10)) ? lmMatch[1].slice(0, 10) : null;
    docEntries.push({ url, lastmod: docusaurusLastmod ?? resolveDocSourceDate(url) });
  }
}

// Construct unified sitemap
const homeLastmod = gitLastModified("site/index.html");
const ideIndexPath = path.join(SITE_SRC, "ide", "index.html");
const hasIdeLanding = fs.existsSync(ideIndexPath);
const ideLastmod = hasIdeLanding ? gitLastModified("site/ide/index.html") : null;
let sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>\n`;
sitemapXml += `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;

// Apex Landing Page
sitemapXml += `  <!-- HardKAS Apex Landing Page -->\n`;
sitemapXml += `  <url>\n    <loc>https://hardkas.dev/</loc>${lastmodXml(homeLastmod)}\n    <changefreq>weekly</changefreq>\n    <priority>1.0</priority>\n  </url>\n`;

// HardKAS IDE Landing Page
if (hasIdeLanding) {
  sitemapXml += `  <!-- HardKAS IDE Landing Page (/ide/) -->\n`;
  sitemapXml += `  <url>\n    <loc>https://hardkas.dev/ide/</loc>${lastmodXml(ideLastmod)}\n    <changefreq>weekly</changefreq>\n    <priority>0.9</priority>\n  </url>\n`;
}

// Documentation URLs
sitemapXml += `  <!-- HardKAS Documentation (/docs/) -->\n`;
for (const { url, lastmod } of docEntries) {
  const priority = url === "https://hardkas.dev/docs/" ? "0.9" : "0.7";
  sitemapXml += `  <url>\n    <loc>${url}</loc>${lastmodXml(lastmod)}\n    <changefreq>weekly</changefreq>\n    <priority>${priority}</priority>\n  </url>\n`;
}
sitemapXml += `</urlset>\n`;

const totalSitemapUrls = docEntries.length + 1 + (hasIdeLanding ? 1 : 0);
fs.writeFileSync(path.join(DIST_SITE, "sitemap.xml"), sitemapXml, "utf8");
console.log(`  ✓ Generated dist/site/sitemap.xml (${totalSitemapUrls} verified URLs)`);

